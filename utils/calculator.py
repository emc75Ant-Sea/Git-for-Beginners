def add_nums(a,b):
        """Return the sum of a and b"""
        return a + b
def divide_nums(a,b):
        """Return the division of a by b"""
        return a / b
def substract_nums(a,b):
        """Return the difference of a by b"""
        return a - b
def multiply_nums(a,b):
        """Return the product of a and b"""
        return a * b
def power(a,b):
        """Return a raise to the power of b """
        return a ** b
